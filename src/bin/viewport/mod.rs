//! 视口进程的三个内聚模块（docs/24 §5）。
//!
//! - [`protocol`]：会话协议 `asset3d.session/1` 的编解码，纯函数、无 IO；
//! - [`gfx`]：wgpu 侧，只认「窗口 → 一帧」；
//! - [`win32`]：命名管道服务端、会话互斥体、管道名规范化，手写 FFI。
//!
//! 三者互不依赖，串起来的是 `asset3d-gui.rs`：它负责 argv 三形态、winit 事件循环，
//! 以及「管道读线程 → 主线程渲染」这条跨线程通路。这样拆分是为了让每一块都能
//! 单独测：协议靠单测、管道靠冒烟、图形靠肉眼。

pub mod gfx;
pub mod protocol;
pub mod win32;
